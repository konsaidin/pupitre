const FORMS = {
  song: { en: ['song', 'songs'], ru: ['песня', 'песни', 'песен'] },
  part: { en: ['part', 'parts'], ru: ['партия', 'партии', 'партий'] },
  fret: { en: ['fret', 'frets'], ru: ['лад', 'лада', 'ладов'] },
} as const;

/** «1 песня, 3 песни, 5 песен» / «1 song, 3 songs»: число со словом в нужной форме. */
export function count(n: number, word: keyof typeof FORMS): string {
  const f = FORMS[word];
  if (currentLang() !== 'ru') return `${n} ${n === 1 ? f.en[0] : f.en[1]}`;
  const tens = n % 100, ones = n % 10;
  const form = tens >= 11 && tens <= 14 ? 2 : ones === 1 ? 0 : ones >= 2 && ones <= 4 ? 1 : 2;
  return `${n} ${f.ru[form]}`;
}
